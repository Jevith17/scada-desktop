function diagnosis = diagnose_fault(residuals, alarms)
% CODE 27 — diagnose_fault.m
% Multi-variable analytical fault isolation and root cause diagnosis
% Supports confidence levels: POSSIBLE / PROBABLE / CONFIRMED

diagnosis = struct();
diagnosis.active_fault = "NONE";
diagnosis.confidence = "NONE";
diagnosis.evidence = {};
diagnosis.detected_at = char(datetime('now', 'Format', "yyyy-MM-dd'T'HH:mm:ss"));

% Multi-variable evidence evaluation
if alarms.temperature
    diagnosis.active_fault = "TEMP_SENSOR_DRIFT";
    diagnosis.confidence = "PROBABLE";
    diagnosis.evidence = { ...
        sprintf("Temperature residual (%+.2f deg C) exceeds threshold (1.5 deg C)", residuals.temperature), ...
        "Thermal energy balance mismatch with dynamic jacket heat model", ...
        "No correlated agitation power anomaly detected" ...
    };
elseif alarms.rpm
    diagnosis.active_fault = "AGITATOR_MOTOR_MALFUNCTION";
    diagnosis.confidence = "CONFIRMED";
    diagnosis.evidence = { ...
        sprintf("Agitator speed residual (%+.1f RPM) exceeds tolerance", residuals.rpm), ...
        "Motor power surge detected while speed commanded at setpoint", ...
        "Viscosity dispersion kinetics showing non-Newtonian deviation" ...
    };
elseif alarms.flow
    diagnosis.active_fault = "FEED_PUMP_MALFUNCTION";
    diagnosis.confidence = "PROBABLE";
    diagnosis.evidence = { ...
        sprintf("Delivered feed flow residual (%+.2f kg/min) below mass balance expected", residuals.flow), ...
        "Feed pump commanded RUNNING while flow rate restricted", ...
        "Tank filling rate below hydrodynamic continuity curve" ...
    };
elseif alarms.level
    diagnosis.active_fault = "TANK_LEAKAGE";
    diagnosis.confidence = "PROBABLE";
    diagnosis.evidence = { ...
        sprintf("Tank mass/level residual (%+.2f%%) indicates unmetered mass depletion", residuals.level), ...
        "Continuity equation violation: dM/dt differs from (Inlet - Outlet)", ...
        "Bottom drain valve confirmed in CLOSED interlock state" ...
    };
elseif alarms.viscosity
    diagnosis.active_fault = "VISCOSITY_QUALITY_DEVIATION";
    diagnosis.confidence = "CONFIRMED";
    diagnosis.evidence = { ...
        sprintf("Viscosity residual (%+.1f cP) deviates from power-law model", residuals.viscosity), ...
        "Out of specification bounds [2800, 3000 cP]", ...
        "Solids content or raw resin batch variance indicated" ...
    };
end
end
